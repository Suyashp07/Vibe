    sections: { speakers: false, agenda: false, gallery: false, faq: true },
    event_type: 'in-person',
    location_name: v.location_name,
    location_address: `${v.location_name}, ${v.city}, India`,
    city: v.city,
    start_at: startIso,
    end_at: endIso,
    timezone: 'Asia/Kolkata',
